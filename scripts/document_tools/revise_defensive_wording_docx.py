def set_font(paragraph) -> None:
    for run in paragraph.runs:
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
        run.font.size = Pt(10.5)


def main() -> None:
    doc = Document(DOCX_PATH)
    changed = []
    for idx, paragraph in enumerate(doc.paragraphs):
        text = paragraph.text.strip()
        if text in REPLACEMENTS:
            paragraph.text = REPLACEMENTS[text]
            set_font(paragraph)
            changed.append(idx)
    if len(changed) != len(REPLACEMENTS):
        missing = len(REPLACEMENTS) - len(changed)
        raise RuntimeError(f"Not all target paragraphs were replaced. Missing: {missing}; changed: {changed}")
    doc.save(DOCX_PATH)
    print(DOCX_PATH)
    print("changed_paragraphs", changed)


if __name__ == "__main__":
    main()
